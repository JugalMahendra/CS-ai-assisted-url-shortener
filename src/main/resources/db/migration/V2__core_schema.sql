-- V2: core URL-shortener schema (short links + click events).

CREATE TABLE short_link (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(16)  NOT NULL,
    original_url    TEXT         NOT NULL,
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    is_custom_alias BOOLEAN      NOT NULL DEFAULT FALSE,
    click_count     BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ,
    CONSTRAINT uq_short_link_code UNIQUE (code),
    CONSTRAINT ck_short_link_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'DISABLED'))
);

-- Efficiently find links that can expire (only rows that actually have an expiry are indexed).
CREATE INDEX ix_short_link_expires_at ON short_link (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE click_event (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_link_id BIGINT      NOT NULL REFERENCES short_link (id) ON DELETE CASCADE,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    referrer      TEXT,
    user_agent    TEXT,
    ip_hash       VARCHAR(64)
);

-- Supports per-link analytics (counts and time-series) ordered by time.
CREATE INDEX ix_click_event_link_time ON click_event (short_link_id, occurred_at);
